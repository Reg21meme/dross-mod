package com.reg21meme.dross.boss.golem.client;

import com.reg21meme.dross.Dross;
import com.reg21meme.dross.boss.golem.CinderColossus;
import com.reg21meme.dross.boss.golem.GolemAction;
import com.reg21meme.dross.boss.golem.GolemDesigns;
import net.minecraft.resources.ResourceLocation;
import software.bernie.geckolib.core.animatable.model.CoreGeoBone;
import software.bernie.geckolib.core.animation.AnimationState;
import software.bernie.geckolib.model.GeoModel;

import java.util.HashMap;
import java.util.Map;

/**
 * Picks each golem's files by its design (see {@link GolemDesigns}): model, animations and its five textures.
 * The files are generated by {@code tools/golems/build.py}.
 * <p>
 * In the fight's Cracking stage it also knocks the design's loose shell plates out of place
 * ({@link GolemDesigns.Design#loosePlates}): each is pushed out and tilted a little as the shell cracks, so lava
 * glows in the gap round it ({@link CinderColossus#crackAmount}).
 */
public class CinderColossusModel extends GeoModel<CinderColossus>
{
    private static final Map<String, Files> FILES = new HashMap<>();

    /** One design's resource locations. */
    public record Files(ResourceLocation model, ResourceLocation animations, ResourceLocation texture,
                        ResourceLocation glow, ResourceLocation flow, ResourceLocation statue, ResourceLocation cracks)
    {
    }

    public static Files files(CinderColossus golem)
    {
        String id = golem.getDesign().id();
        return FILES.computeIfAbsent(id, key -> new Files(
                new ResourceLocation(Dross.MODID, "geo/entity/cinder_colossus/" + key + ".geo.json"),
                new ResourceLocation(Dross.MODID, "animations/entity/cinder_colossus/" + key + ".animation.json"),
                new ResourceLocation(Dross.MODID, "textures/entity/cinder_colossus/" + key + ".png"),
                new ResourceLocation(Dross.MODID, "textures/entity/cinder_colossus/" + key + "_glow.png"),
                new ResourceLocation(Dross.MODID, "textures/entity/cinder_colossus/" + key + "_flow.png"),
                new ResourceLocation(Dross.MODID, "textures/entity/cinder_colossus/" + key + "_statue.png"),
                new ResourceLocation(Dross.MODID, "textures/entity/cinder_colossus/" + key + "_cracks.png")));
    }

    @Override
    public ResourceLocation getModelResource(CinderColossus golem)
    {
        return files(golem).model();
    }

    @Override
    public ResourceLocation getTextureResource(CinderColossus golem)
    {
        return files(golem).texture();
    }

    @Override
    public ResourceLocation getAnimationResource(CinderColossus golem)
    {
        return files(golem).animations();
    }

    /**
     * After the animations have posed the bones: the Cracking stage's loose plates. The offsets are added to this
     * frame's pose only (GeckoLib poses every bone afresh each frame), the same way the generator's previews do it
     * (tools/golems/kit/cracks.py).
     */
    @Override
    public void setCustomAnimations(CinderColossus golem, long instanceId, AnimationState<CinderColossus> state)
    {
        if (golem.getAction() == GolemAction.BREAK_SHELL)
        {
            return; // the plates fly off on their own arcs
        }
        float amount = golem.crackAmount(state.getPartialTick());
        if (amount <= 0.0F)
        {
            return;
        }
        for (GolemDesigns.LoosePlate plate : golem.getDesign().loosePlates())
        {
            float x = Math.max(0.0F, Math.min(1.0F, (amount - plate.from()) / GolemDesigns.LOOSE_POP));
            float k = x * x * (3.0F - 2.0F * x);
            if (k <= 0.0F)
            {
                continue;
            }
            CoreGeoBone bone = this.getAnimationProcessor().getBone(plate.bone());
            if (bone == null)
            {
                continue;
            }
            // Bedrock offsets: GeckoLib stores rotations in radians with x and y flipped, positions as they are.
            bone.setPosX(bone.getPosX() + plate.push().x() * k);
            bone.setPosY(bone.getPosY() + plate.push().y() * k);
            bone.setPosZ(bone.getPosZ() + plate.push().z() * k);
            bone.setRotX(bone.getRotX() - (float) Math.toRadians(plate.tilt().x()) * k);
            bone.setRotY(bone.getRotY() - (float) Math.toRadians(plate.tilt().y()) * k);
            bone.setRotZ(bone.getRotZ() + (float) Math.toRadians(plate.tilt().z()) * k);
            // The setters mark the bone as moved by an animation, which would make GeckoLib keep this frame's pose
            // next frame (piling the offsets up, or showing them on another golem: bones are shared by every golem
            // of a design). Clearing the marks lets GeckoLib pose it afresh next frame.
            bone.resetStateChanges();
        }
    }
}
