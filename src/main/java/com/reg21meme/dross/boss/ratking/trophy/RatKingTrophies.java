package com.reg21meme.dross.boss.ratking.trophy;

import com.reg21meme.dross.boss.trophy.TrophyRewards;
import com.reg21meme.dross.registry.ModBlocks;
import com.reg21meme.dross.registry.ModItems;
import net.minecraft.core.Direction;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.state.BlockState;
import software.bernie.geckolib.core.animation.RawAnimation;

import javax.annotation.Nullable;
import java.util.ArrayList;
import java.util.List;

/**
 * The Rat King trophies: the five designs of a 1x1x1 decorative block ({@code dross:rat_king_trophy}), each a
 * miniature of him (his own model, scaled down, no base) in one pose. The user picked them from ten candidates
 * ({@link RatKingTrophyModels.Model#candidate}). He gives one to every player who helped beat him
 * ({@code RatKing.die}, the design in {@code RatKingTuning.TROPHY_DROP_DESIGN}).
 * <ol>
 *   <li>Fast Asleep: curled up asleep on his side, his staff beside him (Zzz float up)</li>
 *   <li>Tantrum: screeching, his free fist up in the air, red eyes (steam puffs from his ears)</li>
 *   <li>Ground Pound: his staff smashed into the ground, red eyes</li>
 *   <li>Pop Goes the King: popping up out of his hole on a dirt mound, arms flung up</li>
 *   <li>Belly Up: flat on his back, legs in the air, tongue out, X eyes, crown askew</li>
 * </ol>
 * Right-clicking a placed trophy turns it to the next design ({@link #next}), so any trophy can show any of them.
 * The names are lang keys ({@link Design#nameKey}); the shapes come from his model ({@link RatKingTrophyModels},
 * generated by {@code tools/ratking}). This class is the API the trophy showcase uses: {@link #DESIGNS}, {@link #get},
 * {@link Design#blockState} and {@link Design#stack}; he gives his reward with {@link #giveTo} (the shared
 * {@link TrophyRewards}).
 */
public final class RatKingTrophies
{
    // ---------------------------------------------------------------- the block

    /** How long it takes to break (wool is 0.8): any tool, or a bare hand, breaks it in about a second and it drops itself. */
    public static final float HARDNESS = 0.8F;
    /** Explosions can't break it (obsidian is 1200). */
    public static final float BLAST_RESISTANCE = 1200.0F;

    // ---------------------------------------------------------------- changing its pose (right-click)

    /**
     * Right-clicking a placed trophy turns it to the next design (1, 2 ... 5, then 1 again), with a quiet click and a
     * little squeak. Players who can't build there (adventure mode) can't change it, so a map maker's display stays as
     * it is. This is the volume of the click (vanilla's wooden button).
     */
    public static final float CYCLE_CLICK_VOLUME = 0.4F;
    /** Pitch of the click (1 is normal; a little lower, softer). */
    public static final float CYCLE_CLICK_PITCH = 0.8F;
    /** Volume of the squeak under the click (his Plague Rats' squeak, quiet). */
    public static final float CYCLE_SQUEAK_VOLUME = 0.3F;
    /** Pitch of that squeak (higher: a tiny rat). */
    public static final float CYCLE_SQUEAK_PITCH = 1.5F;
    /** Specks of green dust in the little puff it gives off. */
    public static final int CYCLE_DUST_COUNT = 8;
    /** Size of each dust speck (vanilla redstone dust is 1). */
    public static final float CYCLE_DUST_SIZE = 0.7F;
    /** How far the puff spreads round the figure (blocks, each way). */
    public static final double CYCLE_PUFF_SPREAD = 0.25D;
    /** How high in the block the puff's middle is (blocks above its floor). */
    public static final double CYCLE_PUFF_HEIGHT = 0.35D;

    // ---------------------------------------------------------------- its particles (client, now and then)
    // Each is the chance that it happens each time the game picks the block for a random effect: the client does that
    // for blocks near the player, a few times a second right next to it and about once a second a few blocks away.

    /** A tiny green glint at his staff's orb (every design). */
    public static final float ORB_GLINT_CHANCE = 0.1F;
    /** A small "Z" floating up from above his nose (Fast Asleep). */
    public static final float ZZZ_CHANCE = 0.35F;
    /** A puff of steam from each ear (Tantrum). */
    public static final float STEAM_CHANCE = 0.3F;
    /** A pinch of green dust where his staff's foot strikes the ground (Ground Pound). */
    public static final float SLAM_CHANCE = 0.08F;
    /** A crumb of dirt at the rim of his hole (Pop Goes the King). */
    public static final float HOLE_CHANCE = 0.08F;

    /** Lang keys: a design's name is this plus its number; the tooltip line is "No. 5: Belly Up"; and the hint. */
    public static final String NAME_KEY = "block.dross.rat_king_trophy.design_";
    public static final String TOOLTIP_KEY = "block.dross.rat_king_trophy.tooltip";
    public static final String HINT_KEY = "block.dross.rat_king_trophy.hint";
    /** The item tag vanilla uses to give a placed block its properties (and loot tables' copy_state fills in). */
    private static final String BLOCK_STATE_TAG = BlockItem.BLOCK_STATE_TAG;

    /**
     * One trophy design.
     *
     * @param number its number (1 to {@link #count()})
     * @param model  its generated shape: scale, outline, glow, red eyes, light, particle spots
     */
    public record Design(int number, RatKingTrophyModels.Model model)
    {
        /** Its lang key (the name: "Fast Asleep"). */
        public String nameKey()
        {
            return NAME_KEY + this.number;
        }

        /** Its name, for signs and chat. */
        public Component displayName()
        {
            return Component.translatable(this.nameKey());
        }

        /** A word or two about it, for the showcase sign ("Asleep", "Raging"...). */
        public String look()
        {
            return this.model.look();
        }

        /** The block placed with this design, the figure facing {@code facing} (a horizontal direction). */
        public BlockState blockState(Direction facing)
        {
            Direction horizontal = facing.getAxis().isHorizontal() ? facing : Direction.NORTH;
            return ModBlocks.RAT_KING_TROPHY.get().defaultBlockState()
                    .setValue(RatKingTrophyBlock.FACING, horizontal)
                    .setValue(RatKingTrophyBlock.DESIGN, this.number);
        }

        /** One trophy item of this design. */
        public ItemStack stack()
        {
            ItemStack stack = new ItemStack(ModItems.RAT_KING_TROPHY.get());
            CompoundTag state = new CompoundTag();
            state.putString(RatKingTrophyBlock.DESIGN.getName(), Integer.toString(this.number));
            stack.getOrCreateTag().put(BLOCK_STATE_TAG, state);
            return stack;
        }

        /** Its held pose (GeckoLib animation). */
        public RawAnimation animation()
        {
            return ANIMATIONS.get(this.number - 1);
        }
    }

    /** Every design, in order (design 1 first). */
    public static final List<Design> DESIGNS;
    private static final List<RawAnimation> ANIMATIONS;

    static
    {
        List<Design> designs = new ArrayList<>();
        List<RawAnimation> animations = new ArrayList<>();
        for (RatKingTrophyModels.Model model : RatKingTrophyModels.ALL)
        {
            designs.add(new Design(model.number(), model));
            animations.add(RawAnimation.begin().thenLoop(RatKingTrophyModels.ANIMATION_PREFIX + model.number()));
        }
        DESIGNS = List.copyOf(designs);
        ANIMATIONS = List.copyOf(animations);
    }

    private RatKingTrophies()
    {
    }

    /** How many designs there are (5). */
    public static int count()
    {
        return DESIGNS.size();
    }

    /** The design with this number (an unknown number gives design 1). */
    public static Design get(int number)
    {
        return number >= 1 && number <= DESIGNS.size() ? DESIGNS.get(number - 1) : DESIGNS.get(0);
    }

    /** The design after {@code number} when a trophy is right-clicked: 1, 2 ... 5, then 1 again. */
    public static int next(int number)
    {
        return get(number).number() % count() + 1;
    }

    /** The design of a trophy item (design 1 if it doesn't say, for example from {@code /give}). */
    public static int designOf(ItemStack stack)
    {
        CompoundTag tag = stack.getTag();
        if (tag == null || !tag.contains(BLOCK_STATE_TAG))
        {
            return 1;
        }
        String value = tag.getCompound(BLOCK_STATE_TAG).getString(RatKingTrophyBlock.DESIGN.getName());
        try
        {
            return get(Integer.parseInt(value)).number();
        }
        catch (NumberFormatException e)
        {
            return 1;
        }
    }

    /** One trophy item of design {@code number}. */
    public static ItemStack stack(int number)
    {
        return get(number).stack();
    }

    /**
     * His reward: one trophy of design {@code number} for this player, straight into their inventory; with a full
     * inventory dropped a block in front of them, and for a dead player where they died; a dropped one is theirs
     * alone and can't be destroyed ({@link TrophyRewards#giveTo}, shared with the Cinder Colossus).
     *
     * @return the dropped item, or null when it went into their inventory
     */
    @Nullable
    public static ItemEntity giveTo(ServerPlayer player, int number)
    {
        return TrophyRewards.giveTo(player, stack(number));
    }

    /** Drops one trophy of design {@code number} a block in front of the player, theirs alone ({@link TrophyRewards#dropInFront}). */
    public static ItemEntity dropInFront(ServerPlayer player, int number)
    {
        return TrophyRewards.dropInFront(player, stack(number));
    }

    /** Drops one trophy of design {@code number} at the player's feet, theirs alone ({@link TrophyRewards#dropFor}). */
    public static ItemEntity dropFor(ServerPlayer player, int number)
    {
        return TrophyRewards.dropFor(player, stack(number));
    }
}
