package com.reg21meme.dross.boss.trophy.client;

import com.reg21meme.dross.Dross;
import com.reg21meme.dross.boss.trophy.TrophyModels;
import net.minecraft.resources.ResourceLocation;
import software.bernie.geckolib.core.animatable.GeoAnimatable;
import software.bernie.geckolib.model.GeoModel;

/**
 * The Cinder Colossus trophy's files: the boss's model (its own copies, {@code geo/block/colossus_trophy.geo.json} for
 * the placed trophy and {@code geo/item/colossus_trophy.geo.json} for the item: GeckoLib shares a model's bones between
 * everything drawn with it, so the boss, the placed trophies and the items each get their own), the five held poses
 * ({@code animations/block/colossus_trophy}) and the boss's own textures. All generated by {@code tools/golems}.
 */
public class TrophyGeoModel<T extends GeoAnimatable> extends GeoModel<T>
{
    public static final ResourceLocation BLOCK_MODEL = new ResourceLocation(Dross.MODID, "geo/block/colossus_trophy.geo.json");
    public static final ResourceLocation ITEM_MODEL = new ResourceLocation(Dross.MODID, "geo/item/colossus_trophy.geo.json");
    public static final ResourceLocation ANIMATIONS = new ResourceLocation(Dross.MODID, "animations/block/colossus_trophy.animation.json");
    /** The boss's textures: its look, the glowing parts and the Cracking stage's cracks. */
    public static final ResourceLocation TEXTURE = boss("");
    public static final ResourceLocation GLOW = boss("_glow");
    public static final ResourceLocation CRACKS = boss("_cracks");

    private static ResourceLocation boss(String suffix)
    {
        return new ResourceLocation(Dross.MODID, "textures/entity/cinder_colossus/" + TrophyModels.DESIGN_ID + suffix + ".png");
    }

    /** A design's lava streams: hot (the bright bands sliding down) or cool (between them). */
    public static ResourceLocation flow(int design, boolean hot)
    {
        return new ResourceLocation(Dross.MODID, "textures/block/colossus_trophy/design_" + design + (hot ? "_flow.png" : "_flow_base.png"));
    }

    private final ResourceLocation model;

    /** @param model {@link #BLOCK_MODEL} or {@link #ITEM_MODEL} */
    public TrophyGeoModel(ResourceLocation model)
    {
        this.model = model;
    }

    @Override
    public ResourceLocation getModelResource(T animatable)
    {
        return this.model;
    }

    @Override
    public ResourceLocation getTextureResource(T animatable)
    {
        return TEXTURE;
    }

    @Override
    public ResourceLocation getAnimationResource(T animatable)
    {
        return ANIMATIONS;
    }
}
