package com.reg21meme.dross.boss.trophy;

import com.reg21meme.dross.registry.ModBlocks;
import com.reg21meme.dross.registry.ModItems;
import net.minecraft.core.Direction;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.state.BlockState;
import software.bernie.geckolib.core.animation.RawAnimation;

import javax.annotation.Nullable;
import java.util.ArrayList;
import java.util.List;

/**
 * The Cinder Colossus trophies: the five designs of a 1x1x1 decorative block ({@code dross:colossus_trophy}),
 * each a miniature of the boss (its own model, scaled down, no base) in one pose and one look. The boss drops one
 * to every player who helped beat it ({@code CinderColossus.die}, the design in {@code ColossusTuning.DROP_DESIGN}).
 * <ol>
 *   <li>Volcano's Wrath: the volcano lob as the lava leaves its craters (erupted)</li>
 *   <li>Molten Charge: mid-gallop on all fours, head first (lava core)</li>
 *   <li>The Roar: reared up roaring, both fists raised (erupted)</li>
 *   <li>Earthshaker: the ground slam as its fists hit (cracking)</li>
 *   <li>Dormant Shell: crouched in its shell, head bowed (dormant)</li>
 * </ol>
 * Right-clicking a placed trophy turns it to the next design ({@link #next}), so any trophy can show any of them.
 * The names are lang keys ({@link Design#nameKey}); the shapes come from the boss's model ({@link TrophyModels},
 * generated by {@code tools/golems}). This class is the API other areas use (the trophy showcase): {@link #DESIGNS},
 * {@link #get}, {@link Design#blockState} and {@link Design#stack}; the boss gives its reward with {@link #giveTo}.
 */
public final class ColossusTrophies
{
    // ---------------------------------------------------------------- the lava streams (drawn by TrophyLayer)

    /** Seconds a bright band of fresh lava takes to run down a trophy's streams, from the crater to the end. */
    public static final float FLOW_PERIOD_SECONDS = 7.0F;
    /** How long each band is (share of a stream's length, 0 to 1). */
    public static final float FLOW_BAND = 0.18F;
    /** How many bands run down at once (evenly spaced). */
    public static final int FLOW_BANDS = 2;

    // ---------------------------------------------------------------- the block

    /** How long it takes to break (stone is 1.5); any tool, or a bare hand, breaks it and it drops itself. */
    public static final float HARDNESS = 1.5F;
    /** Explosions can't break it (obsidian is 1200). */
    public static final float BLAST_RESISTANCE = 1200.0F;

    // ---------------------------------------------------------------- changing its pose (right-click)

    /**
     * Right-clicking a placed trophy turns it to the next design (1, 2 ... 5, then 1 again), with a quiet stone click.
     * Players who can't build there (adventure mode) can't change it, so a map maker's display stays as it is.
     * This is the volume of the click.
     */
    public static final float CYCLE_CLICK_VOLUME = 0.5F;
    /** Pitch of the click (vanilla's stone button click, pitched down: 1 is normal). */
    public static final float CYCLE_CLICK_PITCH = 0.6F;
    /** Volume of the soft grind of stone under the click (basalt, pitched down). */
    public static final float CYCLE_GRIND_VOLUME = 0.6F;
    /** Pitch of that grind. */
    public static final float CYCLE_GRIND_PITCH = 0.55F;
    /** Specks of ember dust in the little puff it gives off. */
    public static final int CYCLE_DUST_COUNT = 8;
    /** Wisps of smoke in that puff. */
    public static final int CYCLE_SMOKE_COUNT = 3;
    /** Size of each dust speck (vanilla redstone dust is 1). */
    public static final float CYCLE_DUST_SIZE = 0.8F;
    /** How far the puff spreads round the figure (blocks, each way). */
    public static final double CYCLE_PUFF_SPREAD = 0.25D;

    /** Lang key of the tooltip hint ("Right-click to change its pose"). */
    public static final String HINT_KEY = "block.dross.colossus_trophy.hint";

    // ---------------------------------------------------------------- the boss's drop
    // (How it's given and dropped, and its numbers, are shared with every boss: TrophyRewards.)

    /** Lang keys: a design's name is this plus its number; the tooltip line is "No. 1: Volcano's Wrath". */
    public static final String NAME_KEY = "block.dross.colossus_trophy.design_";
    public static final String TOOLTIP_KEY = "block.dross.colossus_trophy.tooltip";
    /** The item tag vanilla uses to give a placed block its properties (and loot tables' copy_state fills in). */
    private static final String BLOCK_STATE_TAG = BlockItem.BLOCK_STATE_TAG;

    /**
     * One trophy design.
     *
     * @param number its number (1 to {@link #count()})
     * @param model  its generated shape: scale, outline, drip spots, craters, look
     */
    public record Design(int number, TrophyModels.Model model)
    {
        /** Its lang key (the name: "Volcano's Wrath"). */
        public String nameKey()
        {
            return NAME_KEY + this.number;
        }

        /** Its name, for signs and chat. */
        public Component displayName()
        {
            return Component.translatable(this.nameKey());
        }

        /** Its look (which form of the boss it shows). */
        public TrophyStyle style()
        {
            return this.model.style();
        }

        /** The block placed with this design, the figure facing {@code facing} (a horizontal direction). */
        public BlockState blockState(Direction facing)
        {
            Direction horizontal = facing.getAxis().isHorizontal() ? facing : Direction.NORTH;
            return ModBlocks.COLOSSUS_TROPHY.get().defaultBlockState()
                    .setValue(ColossusTrophyBlock.FACING, horizontal)
                    .setValue(ColossusTrophyBlock.DESIGN, this.number);
        }

        /** One trophy item of this design. */
        public ItemStack stack()
        {
            ItemStack stack = new ItemStack(ModItems.COLOSSUS_TROPHY.get());
            CompoundTag state = new CompoundTag();
            state.putString(ColossusTrophyBlock.DESIGN.getName(), Integer.toString(this.number));
            stack.getOrCreateTag().put(BLOCK_STATE_TAG, state);
            return stack;
        }

        /** Its held pose (GeckoLib animation). */
        public RawAnimation animation()
        {
            return ANIMATIONS.get(this.number - 1);
        }
    }

    /** Every design, in order (design 1 first). */
    public static final List<Design> DESIGNS;
    private static final List<RawAnimation> ANIMATIONS;

    static
    {
        List<Design> designs = new ArrayList<>();
        List<RawAnimation> animations = new ArrayList<>();
        for (TrophyModels.Model model : TrophyModels.ALL)
        {
            designs.add(new Design(model.number(), model));
            animations.add(RawAnimation.begin().thenLoop(TrophyModels.ANIMATION_PREFIX + model.number()));
        }
        DESIGNS = List.copyOf(designs);
        ANIMATIONS = List.copyOf(animations);
    }

    private ColossusTrophies()
    {
    }

    /** How many designs there are (5). */
    public static int count()
    {
        return DESIGNS.size();
    }

    /** The design with this number (an unknown number gives design 1). */
    public static Design get(int number)
    {
        return number >= 1 && number <= DESIGNS.size() ? DESIGNS.get(number - 1) : DESIGNS.get(0);
    }

    /** The design after {@code number} when a trophy is right-clicked: 1, 2 ... 5, then 1 again. */
    public static int next(int number)
    {
        return get(number).number() % count() + 1;
    }

    /** The design of a trophy item (design 1 if it doesn't say, for example from {@code /give}). */
    public static int designOf(ItemStack stack)
    {
        CompoundTag tag = stack.getTag();
        if (tag == null || !tag.contains(BLOCK_STATE_TAG))
        {
            return 1;
        }
        String value = tag.getCompound(BLOCK_STATE_TAG).getString(ColossusTrophyBlock.DESIGN.getName());
        try
        {
            return get(Integer.parseInt(value)).number();
        }
        catch (NumberFormatException e)
        {
            return 1;
        }
    }

    /** One trophy item of design {@code number}. */
    public static ItemStack stack(int number)
    {
        return get(number).stack();
    }

    /**
     * The boss's reward: one trophy of design {@code number} for this player.
     * <ul>
     *   <li>Straight into their inventory, with vanilla's pickup "pop" ({@code /give}'s sound), if there's room.</li>
     *   <li>If their inventory is full, dropped {@link TrophyRewards#DROP_AHEAD} block in front of them, at their
     *       feet's height ({@link #dropInFront}; at their feet if a block is in the way).</li>
     *   <li>A dead player (waiting to respawn) has no inventory to use: it's dropped where they died ({@link #dropFor}).</li>
     * </ul>
     * A dropped trophy is theirs alone and can't be destroyed (see {@link TrophyRewards}, shared with every boss).
     *
     * @return the dropped item, or null when it went into their inventory
     */
    @Nullable
    public static ItemEntity giveTo(ServerPlayer player, int number)
    {
        return TrophyRewards.giveTo(player, stack(number));
    }

    /**
     * Drops one trophy of design {@code number} {@link TrophyRewards#DROP_AHEAD} block in front of the player (the way
     * they face, level), at about their feet's height; at their feet if that spot is inside a block or a wall is in
     * the way. Theirs alone and indestructible ({@link TrophyRewards#dropInFront}).
     *
     * @return the dropped item, already in the player's world
     */
    public static ItemEntity dropInFront(ServerPlayer player, int number)
    {
        return TrophyRewards.dropInFront(player, stack(number));
    }

    /**
     * Drops one trophy of design {@code number} at the player's feet (where a dead player died), theirs alone and
     * indestructible ({@link TrophyRewards#dropFor}).
     *
     * @return the dropped item, already in the player's world
     */
    public static ItemEntity dropFor(ServerPlayer player, int number)
    {
        return TrophyRewards.dropFor(player, stack(number));
    }
}
