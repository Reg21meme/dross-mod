package com.reg21meme.dross.dimension;

import com.reg21meme.dross.Dross;
import net.minecraft.core.Holder;
import net.minecraft.core.QuartPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.NoiseColumn;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.BiomeSource;
import net.minecraft.world.level.biome.Climate;
import net.minecraft.world.level.levelgen.DensityFunction;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.RandomState;
import net.minecraft.world.level.levelgen.synth.NormalNoise;

/**
 * Reads the Dross's terrain from its noise alone, for any world seed, without generating chunks (for the headless terrain
 * checks and previews). It uses the game's own generator: the same biome source, density functions and noises as real
 * world generation.
 * <ul>
 *   <li>{@link #biome}: the surface biome of a column (read at {@link #BIOME_Y}: the Dross's surface biomes are the same at
 *       every height; only deep under Blightwood is the underground sewers biome, {@link DrossBiomes#SEWERS}).</li>
 *   <li>{@link #height}: the ground height {@code dross:terrain/height} of a column, before the 3D roughness on rocky ground
 *       (the ground's top block is at about this minus one, rounded down).</li>
 *   <li>{@link #function}: any other 2D density function of the terrain (gates, the hub's falloffs...).</li>
 *   <li>{@link #baseHeight} and {@link #column}: the generator's own height and block column of a column (exact, with the
 *       roughness; slower).</li>
 * </ul>
 * Safe to use from several threads at once (each call makes its own working state; the noises don't change).
 */
final class TerrainProbe
{
    /** Biomes are sampled at this height (the Dross's climate doesn't depend on height; the sewers lie far below it). */
    static final int BIOME_Y = 80;

    final ServerLevel dross;
    final long seed;
    final NoiseBasedChunkGenerator generator;
    final RandomState randomState;
    private final BiomeSource biomeSource;
    private final Climate.Sampler sampler;
    private final DensityFunction height;

    private TerrainProbe(ServerLevel dross, long seed, RandomState randomState)
    {
        this.dross = dross;
        this.seed = seed;
        if (!(dross.getChunkSource().getGenerator() instanceof NoiseBasedChunkGenerator noise))
        {
            throw new IllegalStateException("the Dross isn't generated by noise (" + dross.getChunkSource().getGenerator() + ")");
        }
        this.generator = noise;
        this.randomState = randomState;
        this.biomeSource = noise.getBiomeSource();
        this.sampler = randomState.sampler();
        this.height = wired(new ResourceLocation(Dross.MODID, "terrain/height"));
    }

    /** The terrain of a world with this seed (not necessarily the running world's). */
    static TerrainProbe forSeed(ServerLevel dross, long seed)
    {
        NoiseBasedChunkGenerator noise = (NoiseBasedChunkGenerator) dross.getChunkSource().getGenerator();
        RandomState state = RandomState.create(noise.generatorSettings().value(), dross.registryAccess().lookupOrThrow(Registries.NOISE), seed);
        return new TerrainProbe(dross, seed, state);
    }

    /** The running world's own terrain. */
    static TerrainProbe forWorld(ServerLevel dross)
    {
        return new TerrainProbe(dross, dross.getSeed(), dross.getChunkSource().randomState());
    }

    /** The biome of the column (its id). */
    ResourceKey<Biome> biomeKey(int x, int z)
    {
        Holder<Biome> holder = biomeSource.getNoiseBiome(QuartPos.fromBlock(x), QuartPos.fromBlock(BIOME_Y), QuartPos.fromBlock(z), sampler);
        return holder.unwrapKey().orElseThrow();
    }

    /** The biome of the column as its place in {@link DrossBiomes#ALL} (0 Silverwood Forest ... 4 Gravecrags), or -1 for another. */
    int biome(int x, int z)
    {
        return DrossBiomes.ALL.indexOf(biomeKey(x, z));
    }

    /** The ground height {@code dross:terrain/height} at the column (blocks; the top block is at about this minus 1). */
    double height(int x, int z)
    {
        return height.compute(new DensityFunction.SinglePointContext(x, 0, z));
    }

    /** A 2D density function of the Dross's terrain ({@code dross:<path>}), wired to this seed, ready to {@link #at}. */
    DensityFunction function(String path)
    {
        return wired(new ResourceLocation(Dross.MODID, path));
    }

    /** The value of a 2D function from {@link #function} at a column. */
    static double at(DensityFunction function, int x, int z)
    {
        return function.compute(new DensityFunction.SinglePointContext(x, 0, z));
    }

    /** The generator's own height of the column: the Y just above its top solid block (slow: about 0.1 ms). */
    int baseHeight(int x, int z)
    {
        return generator.getBaseHeight(x, z, Heightmap.Types.OCEAN_FLOOR_WG, dross, randomState);
    }

    /** The generator's own blocks of the column, before the surface rules (all Duskstone or air; slow). */
    NoiseColumn column(int x, int z)
    {
        return generator.getBaseColumn(x, z, dross, randomState);
    }

    /** The registered density function {@code id}, with its noises made for this seed (as world generation does). */
    private DensityFunction wired(ResourceLocation id)
    {
        DensityFunction function = dross.registryAccess().registryOrThrow(Registries.DENSITY_FUNCTION)
                .getOrThrow(ResourceKey.create(Registries.DENSITY_FUNCTION, id));
        return function.mapAll(new DensityFunction.Visitor()
        {
            @Override
            public DensityFunction apply(DensityFunction f)
            {
                return f;
            }

            @Override
            public DensityFunction.NoiseHolder visitNoise(DensityFunction.NoiseHolder noise)
            {
                Holder<NormalNoise.NoiseParameters> data = noise.noiseData();
                return new DensityFunction.NoiseHolder(data, randomState.getOrCreateNoise(data.unwrapKey().orElseThrow()));
            }
        });
    }
}
