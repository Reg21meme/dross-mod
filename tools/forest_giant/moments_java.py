"""
Writes src/main/java/com/reg21meme/dross/boss/giant/GiantMoments.java from tools/forest_giant/moments.json (which
mobs.py writes): every look of the Silverwood Giant, its animations' lengths, and the moments the game acts on (a blow's
hit and where it lands, the throw's release, the warning's huff and stamp, the death's fall, its footfalls). mobs.py
runs it at its end; run it on its own after changing moments.json by hand (don't: run mobs.py):

    python tools/forest_giant/moments_java.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
MOMENTS = os.path.join(HERE, "moments.json")
JAVA = os.path.join(ROOT, "src", "main", "java", "com", "reg21meme", "dross", "boss", "giant", "GiantMoments.java")

HEAD = '''package com.reg21meme.dross.boss.giant;

import java.util.List;

/**
 * The Silverwood Giant's looks and the moments of their animations ({@code animation.forest_giant.<name>} in
 * {@code animations/entity/forest_giant/<look>.animation.json}): each animation's length, and when (ticks of the
 * animation's own clock: GeckoLib starts an animation after its controller's blend) and where things happen in it.
 * Points are in the giant's own frame, in blocks: its left (+) or right (-), up from its feet, forward (the way it faces).
 * <p>
 * <b>Generated by {@code tools/forest_giant/moments_java.py} from {@code tools/forest_giant/moments.json} (which
 * {@code tools/forest_giant/mobs.py} writes); don't edit by hand.</b>
 */
public final class GiantMoments
{
    /** A point (or a direction) in the giant's own frame, in blocks. */
    public record Point(double left, double up, double forward)
    {
    }

    /** One animation: its name, its length (seconds and ticks), whether it loops (if not, its last pose stays). */
    public record Anim(String name, float seconds, int ticks, boolean loop)
    {
    }

    /**
     * One look.
     *
     * @param walkPace         blocks a second its walk's feet cover as made (play it faster or slower to match)
     * @param runPace          the same for its run
     * @param walkStep         blocks between two footfalls walking
     * @param runStep          blocks between two footfalls running
     * @param smashLeft        true if its smash comes down with its left arm (G1's fist, G2's shield), else its right
     *                         (G3's club)
     * @param thrownBone       the bone holding what it throws (G1's boulder: {@code weapon}; G2's and G3's rock:
     *                         {@code rock}), hidden from the release
     * @param throwTear        when it tears a rock out of the ground (G1 the new boulder after its throw; G2 and G3 the one
     *                         they throw)
     * @param hiddenBones      bones the renderer hides outside the throw
     */
    public record Look(String id, String label, String mood, List<Anim> anims, List<String> hiddenBones,
                       double walkPace, double runPace, double walkStep, double runStep,
                       int warnFlare, int warnHuff, int warnStamp,
                       int smashHit, boolean smashLeft, Point smashPoint,
                       int sweepHit, Point sweepPoint,
                       int stompHit, Point stompPoint,
                       int throwRelease, int throwTear, String thrownBone, Point releasePoint, Point releaseDirection,
                       int deathRoar, int deathKnees, int deathThud)
    {
        /** The animation of that name, or null. */
        public Anim anim(String name)
        {
            for (Anim a : this.anims)
            {
                if (a.name().equals(name))
                {
                    return a;
                }
            }
            return null;
        }

        /** An animation's length in ticks (20 if it hasn't got it). */
        public int ticks(String name)
        {
            Anim a = this.anim(name);
            return a == null ? 20 : a.ticks();
        }
    }

'''

TAIL = '''
    /** The look a giant wears unless it's told otherwise (the user's pick until they choose: G1). */
    public static final Look DEFAULT = %s;

    /** The look with this id ("hurler", "hoplite", "veteran"), or null. */
    public static Look byId(String id)
    {
        for (Look look : LOOKS)
        {
            if (look.id().equals(id))
            {
                return look;
            }
        }
        return null;
    }

    private GiantMoments()
    {
    }
}
'''


def point(p):
    return f"new Point({p[0]}D, {p[1]}D, {p[2]}D)"


def tick(e, key):
    return int(e.get(f"{key}_tick", 0))      # (0 for a moment of an animation the giant no longer has: its death)


def main():
    data = json.load(open(MOMENTS, encoding="utf-8"))
    out = [HEAD]
    consts = []
    for lid, look in data["looks"].items():
        a = look["anims"]
        anims = ",\n".join(f'                    new Anim("{n}", {e["length"]}F, {e["ticks"]}, {str(e["loop"]).lower()})'
                           for n, e in a.items())
        hidden = ", ".join(f'"{b}"' for b in look["hidden_bones"])
        walk, run = a["walk"], a["run"]
        th = a["throw"]
        tear = th.get("regrab", th.get("tear"))
        const = lid.upper()
        consts.append(const)
        out.append(f'''    /** No. {look["label"]}, {look["mood"]}. */
    public static final Look {const} = new Look("{lid}", "{look["label"]}", "{look["mood"]}", List.of(
{anims}),
            List.of({hidden}),
            {walk["blocks_per_second"]}D, {run["blocks_per_second"]}D, {walk["blocks_per_loop"] / 2.0}D, {run["blocks_per_loop"] / 2.0}D,
            {tick(a["warn"], "flare")}, {tick(a["warn"], "huff")}, {tick(a["warn"], "stamp")},
            {tick(a["smash"], "hit")}, {str(a["smash"]["side"] == "left").lower()}, {point(a["smash"]["hit_point"])},
            {tick(a["sweep"], "hit")}, {point(a["sweep"]["hit_point"])},
            {tick(a["stomp"], "hit")}, {point(a["stomp"]["hit_point"])},
            {tick(th, "release")}, {int(round(tear * 20))}, "{th["thrown_bone"]}", {point(th["release_point"])},
            {point(th["release_direction"])},
            {tick(a.get("death", {}), "roar")}, {tick(a.get("death", {}), "knees")}, {tick(a.get("death", {}), "thud")});

''')
    out.append(f"    /** Every look, G1 first. */\n    public static final List<Look> LOOKS = List.of({', '.join(consts)});\n")
    out.append(TAIL % data["default_look"].upper())
    os.makedirs(os.path.dirname(JAVA), exist_ok=True)
    with open(JAVA, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print(f"wrote {os.path.relpath(JAVA, ROOT)} ({len(consts)} looks)")


if __name__ == "__main__":
    main()
