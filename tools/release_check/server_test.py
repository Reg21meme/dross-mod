"""Runs a real Forge 1.20.1 dedicated server with the Dross jar (and any other mods), makes a new world, and drives it
through the console: the cathedral's, the trader's and the hub's land generated by forceloading, checked with commands,
the Dross explored in a few far places, tick times read with /forge tps. Writes <out>/report.txt and keeps the log.

Usage: server_test.py <server dir> <out dir> <seed> <mods dir>... [--config <dross-common.toml>] [--keep-world]
"""
import os
import queue
import re
import shutil
import subprocess
import sys
import threading
import time

args = sys.argv[1:]
config_file = None
keep_world = "--keep-world" in args
if keep_world:
    args.remove("--keep-world")
if "--config" in args:
    i = args.index("--config")
    config_file = args[i + 1]
    del args[i:i + 2]
server_dir, out_dir, seed = args[0], args[1], args[2]
mod_dirs = args[3:]
os.makedirs(out_dir, exist_ok=True)
report = []


def note(line):
    stamp = time.strftime("%H:%M:%S")
    print(stamp, line, flush=True)
    report.append(stamp + " " + line)


# ---- a clean server: no world, no logs, only these mods, this config
for d in (["logs", "crash-reports", "mods", "config", "defaultconfigs"] + ([] if keep_world else ["world"])):
    shutil.rmtree(os.path.join(server_dir, d), ignore_errors=True)
os.makedirs(os.path.join(server_dir, "mods"))
mods = []
for md in mod_dirs:
    for f in sorted(os.listdir(md)):
        if f.endswith(".jar"):
            shutil.copy(os.path.join(md, f), os.path.join(server_dir, "mods", f))
            mods.append(f)
note("mods: " + ", ".join(mods))
if config_file:
    os.makedirs(os.path.join(server_dir, "config"))
    shutil.copy(config_file, os.path.join(server_dir, "config", "dross-common.toml"))
    note("config: " + open(config_file, encoding="utf-8").read().replace("\n", " | "))
open(os.path.join(server_dir, "eula.txt"), "w").write("eula=true\n")
open(os.path.join(server_dir, "server.properties"), "w").write(
    "level-seed=%s\nonline-mode=false\nview-distance=10\nsimulation-distance=8\nspawn-protection=0\nmotd=dross test\n"
    "max-tick-time=60000\nenable-rcon=false\nsync-chunk-writes=true\n" % seed)
open(os.path.join(server_dir, "user_jvm_args.txt"), "w").write("-Xmx6G\n-Xms2G\n")
note("seed " + seed)

# ---- start it
win_args = "@libraries/net/minecraftforge/forge/1.20.1-47.4.10/win_args.txt"
proc = subprocess.Popen(["java", "@user_jvm_args.txt", win_args, "nogui"], cwd=server_dir, stdin=subprocess.PIPE,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace", bufsize=1)
lines = queue.Queue()
all_lines = []
console = open(os.path.join(out_dir, "console.txt"), "w", encoding="utf-8")


def reader():
    for line in proc.stdout:
        line = line.rstrip("\n")
        console.write(line + "\n")
        console.flush()
        all_lines.append(line)
        lines.put(line)
    lines.put(None)


threading.Thread(target=reader, daemon=True).start()
started = time.time()


def wait_for(pattern, timeout, after=None):
    """The first line from now on matching the pattern (a regex), or None after timeout seconds."""
    rx = re.compile(pattern)
    end = time.time() + timeout
    while time.time() < end:
        try:
            line = lines.get(timeout=1)
        except queue.Empty:
            if proc.poll() is not None:
                return None
            continue
        if line is None:
            return None
        if rx.search(line):
            return line
    return None


def drain():
    while True:
        try:
            if lines.get_nowait() is None:
                return
        except queue.Empty:
            return


def send(cmd):
    drain()
    proc.stdin.write(cmd + "\n")
    proc.stdin.flush()


def ask(cmd, pattern, timeout=20):
    send(cmd)
    return wait_for(pattern, timeout)


def find_logged(pattern):
    rx = re.compile(pattern)
    for line in all_lines:
        m = rx.search(line)
        if m:
            return m
    return None


def tps(label):
    send("forge tps")
    got = []
    end = time.time() + 15
    while time.time() < end and len(got) < 6:
        line = wait_for(r"Mean tick time|Overall", 3)
        if line:
            got.append(line.split("]: ", 1)[-1])
    note("tps (" + label + "): " + " || ".join(got))


done = wait_for(r"Done \(\d", 1800)
if not done:
    note("FAIL: the server never finished starting (" + str(round(time.time() - started)) + " s); exit " + str(proc.poll()))
else:
    note("started in %d s: %s" % (time.time() - started, done.split("]: ", 1)[-1]))

    # The site and the trader, from the seed (logged in the background as the world loads)
    deadline = time.time() + 300
    site = trader = None
    while time.time() < deadline and (site is None or trader is None):
        site = site or find_logged(r"Dross portal site: .*?site column (-?\d+) (-?\d+), ground level y (-?\d+), (\d+) blocks from the spawn point.*?\(rule (\d)")
        trader = trader or find_logged(r"Rift Chapel, from the seed: the Rift Chapel at (-?\d+), (-?\d+), (-?\d+)(.*)")
        if site is None or trader is None:
            time.sleep(2)
    for line in all_lines:
        if "possible villages within" in line or "Trader's village, try" in line or "trader's chapel stands" in line \
                or "A new world: its settings" in line or "keeps the settings" in line:
            note("log: " + line.split("]: ", 1)[-1][:300])
    tps("after start")

    # ---- the cathedral
    if site:
        x, z, g, dist, rung = (int(v) for v in site.groups())
        note("cathedral: site column %d %d, ground %d, %d blocks from spawn, rule %d" % (x, z, g, dist, rung))
        t0 = time.time()
        ask("forceload add %d %d %d %d" % (x - 40, z - 56, x + 40, z + 56), r"forceload|Marked|chunk")
        frames = None
        while time.time() - t0 < 600:
            r = ask("clone %d %d %d %d %d %d %d 290 %d filtered dross:dross_portal_frame" % (x - 4, g - 6, z - 4, x + 4, g + 14, z + 4, x - 4, z - 4),
                    r"cloned|not loaded|No blocks|Too many", 30)
            if r and "Successfully cloned" in r:
                frames = int(re.search(r"cloned (\d+)", r).group(1))
                break
            if r and "No blocks" in r:
                frames = 0
                break
            time.sleep(5)
        note("cathedral: %s frame blocks round the site column (%d s after forceloading)" % (frames, time.time() - t0))
        if frames is None or frames < 14:
            note("FAIL: the cathedral's frame isn't there")
        tps("cathedral loaded")
        ask("forceload remove all", r"forceload|Unmarked|chunk")
    else:
        note("FAIL: no site logged")

    # ---- the trader
    if trader:
        tx, ty, tz = (int(v) for v in trader.groups()[:3])
        note("trader: spot %d %d %d%s" % (tx, ty, tz, trader.group(4)[:200]))
        t0 = time.time()
        ask("forceload add %d %d %d %d" % (tx - 48, tz - 48, tx + 48, tz + 48), r"forceload|Marked|chunk")
        count = None
        while time.time() - t0 < 600:
            r = ask("execute if entity @e[type=dross:dross_trader]", r"Test (passed|failed)", 20)
            if r and "passed" in r:
                count = int(re.search(r"count: (\d+)", r).group(1))
                break
            time.sleep(5)
        note("trader: %s trader(s) in the loaded world (%d s after forceloading)" % (count, time.time() - t0))
        time.sleep(20)
        r = ask("execute if entity @e[type=dross:dross_trader]", r"Test (passed|failed)", 20)
        later = int(re.search(r"count: (\d+)", r).group(1)) if r and "passed" in r else 0
        note("trader: %d trader(s) 20 s later" % later)
        if count != 1 or later != 1:
            note("FAIL: not exactly one trader")
        r = ask("execute if entity @e[type=minecraft:villager,x=%d,y=%d,z=%d,distance=..120]" % (tx, ty, tz), r"Test (passed|failed)", 20)
        note("trader's village: " + (r.split("]: ", 1)[-1] if r else "no answer"))
        tps("trader loaded")
        ask("forceload remove all", r"forceload|Unmarked|chunk")
    else:
        note("FAIL: no trader logged")

    # ---- the hub
    t0 = time.time()
    ask("execute in dross:dross run forceload add -96 -96 96 96", r"forceload|Marked|chunk")
    surv = None
    while time.time() - t0 < 900:
        r = ask("execute in dross:dross if entity @e[type=dross:survivor]", r"Test (passed|failed)", 20)
        if r and "passed" in r:
            surv = int(re.search(r"count: (\d+)", r).group(1))
            if surv >= 2:
                break
        time.sleep(5)
    note("hub: %s survivor(s) (%d s after forceloading 169 chunks)" % (surv, time.time() - t0))
    r = ask("execute in dross:dross run clone -4 40 -3 4 200 3 30 40 -3 filtered dross:dross_portal", r"cloned|not loaded|No blocks", 60)
    note("hub: exit portal blocks: " + (r.split("]: ", 1)[-1] if r else "no answer"))
    if surv != 2 or not r or "Successfully cloned" not in r:
        note("FAIL: the hub isn't whole")
    tps("hub loaded")
    ask("execute in dross:dross run forceload remove all", r"forceload|Unmarked|chunk")

    # ---- the Dross further out: 256 chunks at each spot, all biomes' worth
    for (ax, az) in [(1100, 0), (0, 1100), (-1100, 0), (0, -1100), (2200, 2200), (-2600, 1800)]:
        t0 = time.time()
        ask("execute in dross:dross run forceload add %d %d %d %d" % (ax - 120, az - 120, ax + 119, az + 119), r"forceload|Marked|chunk|Too many")
        ok = False
        while time.time() - t0 < 900:
            r = ask("execute in dross:dross if loaded %d 64 %d" % (ax + 112, az + 112), r"Test (passed|failed)", 20)
            if r and "passed" in r:
                ok = True
                break
            time.sleep(5)
        note("dross %d %d: 256 chunks %s in %d s" % (ax, az, "made" if ok else "NOT made", time.time() - t0))
        if not ok:
            note("FAIL: the Dross at %d %d wasn't made in 15 minutes" % (ax, az))
        tps("dross %d %d" % (ax, az))
        ask("execute in dross:dross run forceload remove all", r"forceload|Unmarked|chunk")

    # ---- the Overworld further out
    t0 = time.time()
    ask("forceload add 1800 1800 2039 2039", r"forceload|Marked|chunk")
    ok = False
    while time.time() - t0 < 900:
        r = ask("execute if loaded 2032 64 2032", r"Test (passed|failed)", 20)
        if r and "passed" in r:
            ok = True
            break
        time.sleep(5)
    note("overworld 1800 1800: 256 chunks %s in %d s" % ("made" if ok else "NOT made", time.time() - t0))
    tps("overworld far")
    ask("forceload remove all", r"forceload|Unmarked|chunk")

    # ---- the showcase-only galleries are left out of the jar (boss/ShowcaseOnly; November 7, 2026): their commands too
    for gallery, built in (("cinder_wastes", "Built the fire servant gallery"), ("rimefall", "Rimefall gallery|Built the Rimefall")):
        time.sleep(2)  # (the last command's lines all in first: drained before this one)
        r = ask("dross showcase boss_designs " + gallery, r"Unknown or incomplete command|Incorrect argument|" + built, 20)
        if r and ("Unknown" in r or "Incorrect" in r):
            note("showcase gallery %s: not offered (its models aren't in the jar)" % gallery)
        else:
            note("FAIL: the showcase gallery %s is still offered by the jar: %s" % (gallery, r))

    t0 = time.time()
    send("save-all")
    wait_for(r"Saved the game", 300)
    send("stop")

try:
    proc.wait(timeout=600)
except subprocess.TimeoutExpired:
    note("FAIL: the server didn't stop in 10 minutes; killed")
    proc.kill()
note("server exited %s after %d s in all" % (proc.poll(), time.time() - started))
time.sleep(1)

# ---- what the log says
errors = [l for l in all_lines if re.search(r"/(ERROR|FATAL)\]", l)]
warns = [l for l in all_lines if "/WARN]" in l]
dross_warns = [l for l in warns if "dross" in l.lower()]
overload = [l for l in all_lines if "Can't keep up" in l]
exceptions = [l for l in all_lines if re.search(r"Exception|Error:", l) and "/INFO]" not in l]
note("log: %d lines, %d ERROR/FATAL, %d WARN (%d mention dross), %d 'Can't keep up', %d exception lines"
     % (len(all_lines), len(errors), len(warns), len(dross_warns), len(overload), len(exceptions)))
for l in errors[:25]:
    note("  ERROR: " + l[:400])
for l in dross_warns[:25]:
    note("  WARN: " + l[:400])
for l in overload[:10]:
    note("  " + l[:300])
crash = os.path.join(server_dir, "crash-reports")
if os.path.isdir(crash) and os.listdir(crash):
    note("FAIL: crash reports: " + ", ".join(os.listdir(crash)))
    for f in os.listdir(crash):
        shutil.copy(os.path.join(crash, f), out_dir)
for f in ["latest.log", "debug.log"]:
    p = os.path.join(server_dir, "logs", f)
    if os.path.exists(p):
        shutil.copy(p, out_dir)
fails = [r for r in report if "FAIL" in r]
note("RESULT: " + ("ALL GOOD" if not fails else "%d problem(s)" % len(fails)))
open(os.path.join(out_dir, "report.txt"), "w", encoding="utf-8").write("\n".join(report) + "\n")
